-- GIF-анимации (в среднем ~280 КБ, до 530 КБ) заменены на короткие
-- зацикленные MP4 (в среднем ~30 КБ) — тот же контент, перекодированный
-- через ffmpeg (H.264), без видимой потери качества, но в ~10-15 раз
-- легче. На медленной сети (GitHub Pages из России) это была основная
-- причина долгой загрузки анимации при старте тренировки. Файлы на
-- хостинге уже заменены (web/exercises/*.mp4 вместо *.gif) — здесь
-- просто обновляем расширение в уже сохранённых ссылках.
UPDATE exercises SET gif_url = REGEXP_REPLACE(gif_url, '\.gif$', '.mp4')
WHERE gif_url LIKE '%.gif';
